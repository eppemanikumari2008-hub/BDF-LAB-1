// basic-server.js
// Implementation of a plain Node.js HTTP server using the built-in http module.

const http = require('http');

const PORT = process.env.PORT || 3000;

const server = http.createServer((req, res) => {
  res.writeHead(200, { 'Content-Type': 'text/plain; charset=utf-8' });
  res.end('Hello');
});

server.listen(PORT, () => {
  console.log(`[Basic HTTP Server] Server is running on http://localhost:${PORT}`);
});

server.on('error', (err) => {
  if (err.code === 'EADDRINUSE') {
    console.error(`Port ${PORT} is already in use. Please free the port or choose a different port.`);
  } else {
    console.error('Server encountered an error:', err.message);
  }
});
